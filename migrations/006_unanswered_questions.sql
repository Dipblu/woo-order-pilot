create table if not exists unanswered_questions (
  id               bigserial primary key,
  question         text,
  session_id       text,
  reason           text,
  similarity_score double precision,
  answer_given     text,
  created_at       timestamptz not null default now()
);

alter table unanswered_questions enable row level security;

-- Both logging nodes use RETURNING id, created_at, so id must exist and be
-- generated by the database -- neither node supplies it. Confirmed live as
-- unanswered_questions_pkey.
--
-- reason is an open text column, not an enum. Two values are written today
-- ('below_threshold', 'low_confidence_answer'). Left unconstrained because a
-- client deployment may log other kinds of miss, and a CHECK constraint would
-- fail the INSERT at runtime rather than at deploy time.
--
-- similarity_score is the top-hit cosine similarity from Check Relevance
-- (topSimilarity), not an average across the retrieved chunks.
--
-- WHAT THIS TABLE CAN AND CANNOT TELL YOU: low-confidence rows are filtered at
-- write time -- "Should Log Low Confidence?" only logs when topSimilarity <
-- 0.5. So the stored distribution is truncated, and it cannot be used to check
-- whether the 0.5 floor is set too LOW. To re-tune the floor against real
-- data, log every candidate and add a boolean column marking the flagged ones,
-- rather than filtering before the insert.

